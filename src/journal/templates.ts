/**
 * 일기 문장 은행.
 *
 * 목소리 규칙 (기술보다 중요하다):
 *  - 1인칭, 짧은 문장, 세 문장 이내
 *  - 숫자 없음. "네 번 쓰다듬었다"는 로그지 일기가 아니다
 *  - 비난 없음. "안 왔다"가 아니라 "조용했다"
 *  - 감각적이고 사소하게. 큰 사건보다 창가의 빛
 *  - 가끔 틀리게 — 인격은 정확한 관찰이 아니라 '귀여운 오해'에서 나온다
 */

export interface Template {
  id: string;
  text: string;
}

/**
 * ★ 햄스터가 그녀를 부르는 말은 시간이 지나면서 바뀐다.
 *   큰 손 → 그 사람 → 내 사람
 * 관계의 변화를 설명하지 않고 어휘로만 보여준다. 이게 가장 조용하고 가장 세다.
 */
export function herWord(dayNumber: number): string {
  if (dayNumber <= 3) return '큰 손';
  if (dayNumber <= 20) return '그 사람';
  return '내 사람';
}

